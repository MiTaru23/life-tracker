import { useMemo } from 'react'
import type {
  Bodyweight,
  Goal,
  Habit,
  HabitCheck,
  Hobby,
  JournalEntry,
  LearningItem,
  Session,
  Suggestion,
  Workout,
} from '../lib/db'
import { useAlive } from '../lib/hooks'
import { setSuggestionState } from '../lib/repo'
import { computeRules, type RuleHit } from '../lib/rules'
import { Empty } from '../ui'

const AREA_GLYPH: Record<string, string> = {
  sport: '▦',
  learning: '◈',
  hobby: '♪',
  journal: '✎',
  general: '◆',
}

export default function SuggestionsPage() {
  const journal = useAlive<JournalEntry>('journal')
  const workouts = useAlive<Workout>('workouts')
  const learning = useAlive<LearningItem>('learning')
  const hobbies = useAlive<Hobby>('hobbies')
  const sessions = useAlive<Session>('sessions')
  const habits = useAlive<Habit>('habits')
  const habitChecks = useAlive<HabitCheck>('habitChecks')
  const goals = useAlive<Goal>('goals')
  const bodyweights = useAlive<Bodyweight>('bodyweights')
  const stored = useAlive<Suggestion>('suggestions')

  const loaded = [journal, workouts, learning, hobbies, sessions, habits, habitChecks, goals, bodyweights, stored].every(
    (x) => x !== undefined,
  )

  const stateById = useMemo(() => new Map((stored ?? []).map((s) => [s.id, s])), [stored])

  const ruleHits = useMemo(() => {
    if (!loaded) return []
    return computeRules({
      journal: journal!,
      workouts: workouts!,
      learning: learning!,
      hobbies: hobbies!,
      sessions: sessions!,
      habits: habits!,
      habitChecks: habitChecks!,
      goals: goals!,
      bodyweights: bodyweights!,
    }).filter((h) => !stateById.get(h.id)?.dismissed)
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [loaded, journal, workouts, learning, hobbies, sessions, habits, habitChecks, goals, bodyweights, stateById])

  // AI suggestions live only in the table (written by the PC uplink).
  const aiHits = useMemo(
    () => (stored ?? []).filter((s) => s.source === 'ai' && !s.deleted && !s.dismissed).sort((a, b) => b.updatedAt - a.updatedAt),
    [stored],
  )

  if (!loaded) return null

  return (
    <section>
      {aiHits.length > 0 && (
        <>
          <div className="eyebrow">weekly review · generated by claude</div>
          {aiHits.map((s) => (
            <Card key={s.id} hit={s} state={s} ai />
          ))}
        </>
      )}

      <div className="eyebrow">nudges · {ruleHits.length}</div>
      {!ruleHits.length && <Empty>all clear — nothing needs your attention right now</Empty>}
      {ruleHits.map((h) => (
        <Card key={h.id} hit={h} state={stateById.get(h.id)} />
      ))}
    </section>
  )
}

function Card({
  hit,
  state,
  ai,
}: {
  hit: RuleHit | Suggestion
  state?: Suggestion
  ai?: boolean
}) {
  const fb = state?.feedback
  const base = { id: hit.id, area: hit.area, title: hit.title, body: hit.body, source: ai ? ('ai' as const) : ('rule' as const) }

  return (
    <div className="card intel">
      <div className="intel-head">
        <span className="intel-glyph">{AREA_GLYPH[hit.area] ?? '◆'}</span>
        <strong className="grow">{hit.title}</strong>
        {ai && <span className="src">ai</span>}
        <button className="x" title="Dismiss" onClick={() => setSuggestionState(base, { dismissed: true })}>×</button>
      </div>
      <p className="intel-body">{hit.body}</p>
      <div className="intel-foot">
        <button
          className={`vote${fb === 'up' ? ' on' : ''}`}
          aria-pressed={fb === 'up'}
          onClick={() => setSuggestionState(base, { feedback: fb === 'up' ? undefined : 'up' })}
        >
          👍 helpful
        </button>
        <button
          className={`vote${fb === 'down' ? ' on down' : ''}`}
          aria-pressed={fb === 'down'}
          onClick={() => setSuggestionState(base, { feedback: fb === 'down' ? undefined : 'down' })}
        >
          👎 not useful
        </button>
      </div>
    </div>
  )
}
